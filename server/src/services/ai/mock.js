/**
 * A deterministic offline provider.
 *
 * Free tiers are rate limited and slow, and burning quota on UI work is a bad
 * trade — most development touches the model incidentally, not deliberately.
 * This returns plausible, stable results with no network at all, so the whole
 * app can be built, demoed and tested without a key.
 *
 * It is not a model. It never looks at the image. Anything it produces is
 * fiction, and it says so in the summary, so nobody mistakes a mock run for a
 * real classification during a demo.
 */
const CATEGORIES = [
  { name: "Pothole", dept: "Roads & Infrastructure", severity: "high", score: 62,
    factors: [["On a main carriageway", 25], ["Deep enough to damage a wheel", 22], ["Heavy footfall nearby", 15]] },
  { name: "Garbage overflow", dept: "Solid Waste Management", severity: "high", score: 58,
    factors: [["Bin overflowing onto the footpath", 24], ["Near a food market", 20], ["Attracting strays", 14]] },
  { name: "Water leakage", dept: "Water Supply", severity: "medium", score: 47,
    factors: [["Continuous flow", 20], ["Pooling on the road", 17], ["No immediate hazard", 10]] },
  { name: "Broken streetlight", dept: "Street Lighting", severity: "medium", score: 41,
    factors: [["Unlit stretch after dark", 22], ["Residential street", 12], ["No exposed wiring", 7]] },
  { name: "Open manhole", dept: "Roads & Infrastructure", severity: "critical", score: 88,
    factors: [["Uncovered and unguarded", 40], ["On a pedestrian route", 28], ["Near a school", 20]] },
  { name: "Blocked drain", dept: "Storm Water Drains", severity: "high", score: 55,
    factors: [["Standing water", 22], ["Monsoon season", 18], ["Known flooding point", 15]] },
];

/** Same image in, same result out — so a demo is repeatable. */
function pick(seed) {
  let hash = 0;
  for (let i = 0; i < seed.length; i += 1) hash = (hash * 31 + seed.charCodeAt(i)) >>> 0;
  return CATEGORIES[hash % CATEGORIES.length];
}

export const mock = {
  label: "Mock (offline)",
  envKey: null,
  vision: true,
  // Whether it can be shown two images and reason about both.
  vision_comparison: true,
  defaultModel: "deterministic",
  configured: () => true,

  async complete({ messages }) {
    const last = messages[messages.length - 1];
    const content = last?.content;

    const text = typeof content === "string"
      ? content
      : content.filter((b) => b.type === "text").map((b) => b.text).join("\n");

    const image = typeof content === "string"
      ? null
      : content.find((b) => b.type === "image");

    // A little latency, so loading states are exercised rather than skipped.
    await new Promise((r) => setTimeout(r, 220));

    /* ---- photo classification ---- */
    if (image && /category/i.test(text)) {
      const c = pick(image.data.slice(0, 64));

      // Roughly one in seven mock runs returns "not a civic issue", so that
      // path gets exercised during development instead of only in production
      // the first time somebody photographs their lunch.
      if (c.name === "Open manhole" && image.data.length % 7 === 0) {
        return JSON.stringify({
          category: "Other",
          confidence: 88,
          department: "Ward Office — triage",
          severity: "low",
          severity_score: 5,
          severity_factors: [],
          authenticity: "undetermined",
          authenticity_confidence: 0,
          authenticity_notes: ["Mock provider — no image analysis was performed."],
          summary: "This does not appear to show a civic problem.",
          description:
            "The photograph does not show anything on a public road, footpath or municipal asset. " +
            "Mock output — no image analysis was performed.",
          observations: [],
          recommended_action: null,
          is_civic_issue: false,
          not_civic_reason: "The subject is not a public asset or public space.",
        });
      }
      return JSON.stringify({
        category: c.name,
        confidence: 91,
        department: c.dept,
        severity: c.severity,
        severity_score: c.score,
        severity_factors: c.factors.map(([factor, points]) => ({ factor, points })),
        authenticity: "likely_genuine",
        authenticity_confidence: 84,
        authenticity_notes: ["Mock provider — no image analysis was performed."],
        summary: `${c.name} reported. Mock output, not a real classification.`,
        description:
          `A ${c.name.toLowerCase()} is visible in the photograph. The extent appears consistent ` +
          `with a ${c.severity} severity report, and the surroundings suggest regular pedestrian ` +
          `use. This text is generated by the offline mock provider and describes nothing that was ` +
          `actually in your image.`,
        observations: c.factors.map(([f]) => f),
        recommended_action: "Mock provider — no recommendation was derived from the photograph.",
        is_civic_issue: true,
        not_civic_reason: null,
      });
    }

    /* ---- before/after comparison ---- */
    if (image && /BEFORE|AFTER/i.test(text)) {
      return JSON.stringify({
        scene_match: 89,
        change_detected: true,
        verdict: "likely_completed",
        summary: "Mock provider. No comparison was performed; a reviewer should check the photos.",
      });
    }

    /* ---- cluster brief ---- */
    if (/summary.*action.*risk/is.test(text)) {
      return JSON.stringify({
        summary:
          "Reports in this group arrived over several days from distinct residents within a short radius. " +
          "The pattern suggests a single underlying fault rather than separate incidents. " +
          "This text is mock output and is not derived from the data.",
        action: "Send one crew to the centroid within 24 hours rather than treating each report separately.",
        risk: "Left alone, the group will keep growing and each report restarts its own clock.",
      });
    }

    /* ---- admin assistant / daily brief ---- */
    if (/headline/i.test(text)) {
      return JSON.stringify({
        headline: "Mock provider — no analysis performed",
        findings: [
          { label: "AI provider", value: "mock", note: "set AI_PROVIDER to use a real one" },
        ],
        reading:
          "The offline provider is active, so nothing here reflects your data. Switch AI_PROVIDER " +
          "to gemini, groq or ollama for real answers.",
        action: "",
        items: [
          {
            tag: "Operations",
            severity: "low",
            headline: "Offline provider is active",
            detail:
              "Classification and briefs are returning fixed placeholder text. Set a real AI provider " +
              "in server/.env before relying on any of it.",
          },
        ],
      });
    }

    return "OK";
  },
};
